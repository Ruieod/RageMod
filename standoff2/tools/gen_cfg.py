#!/usr/bin/env python3
"""schema.json -> Cfg.java (UI side) + cfg_gen.h (native side). Single source of truth for every setting."""
import json, re, sys, os

T_TOGGLE, T_SLIDER, T_COMBO, T_COLOR, T_HIDDEN = 0, 1, 2, 3, 4
TYPES = {"toggle": T_TOGGLE, "slider": T_SLIDER, "combo": T_COMBO, "color": T_COLOR, "hidden": T_HIDDEN}
CATS = ["Pistol", "SMG", "Rifle", "Sniper", "Shotgun"]


def cname(i):
    return re.sub(r"[^A-Za-z0-9]+", "_", i).upper()


def jstr(s):
    return json.dumps(s, ensure_ascii=True)


def load(path):
    d = json.load(open(path, encoding="utf-8"))
    weapons = d["weapons"]
    items = []
    slot = 0
    for ti, tab in enumerate(d["tabs"]):
        for gi, grp in enumerate(tab["groups"]):
            for it in grp["items"]:
                it = dict(it)
                it["tab"], it["grp"] = ti, gi
                t = TYPES[it["t"]]
                it["type"] = t
                if it["id"] == "wpn.manual":
                    it["o"] = ["Auto-detect"] + [w["name"] for w in weapons]
                it["slot"] = slot
                slot += 4 if t == T_COLOR else 1
                items.append(it)
    ids = {it["id"]: it for it in items}
    for it in items:
        dep = it.get("dep")
        if dep and dep not in ids:
            raise SystemExit("bad dep %s -> %s" % (it["id"], dep))
    widx = 0
    for it in items:
        if it.get("w"):
            if it["type"] == T_COLOR:
                raise SystemExit("weapon scope on color not supported: " + it["id"])
            it["widx"] = widx
            widx += 1
        else:
            it["widx"] = -1
    return d, weapons, items, ids, slot, widx


def gen_java(d, weapons, items, ids, n, wk):
    o = []
    o.append("// GENERATED by tools/gen_cfg.py from config/schema.json - do not edit")
    o.append("package rage.so2.gen;\n")
    o.append("public final class Cfg {")
    o.append("    private Cfg() {}\n")
    o.append("    public static final int T_TOGGLE = 0, T_SLIDER = 1, T_COMBO = 2, T_COLOR = 3, T_HIDDEN = 4;")
    o.append("    public static final int N = %d;" % n)
    o.append("    public static final int W_COUNT = %d;" % len(weapons))
    o.append("    public static final int WK = %d;" % wk)
    o.append("    public static final int W_STRIDE = %d;" % (1 + wk))
    o.append("    public static final int W_BASE = N;")
    o.append("    public static final int TOTAL = N + W_COUNT * W_STRIDE;\n")
    for it in items:
        o.append("    public static final int %s = %d;" % (cname(it["id"]), it["slot"]))
    o.append("")
    o.append("    public static final class Item {")
    o.append("        public final String id, label, unit; public final int type, slot, widx, dep, tab, grp;")
    o.append("        public final float def, min, max, step; public final float[] defColor; public final String[] opts;")
    o.append("        Item(String id, int type, String label, int slot, int widx, int dep, int tab, int grp, float def, float min, float max, float step, String unit, float[] dc, String[] opts) {")
    o.append("            this.id = id; this.type = type; this.label = label; this.slot = slot; this.widx = widx; this.dep = dep; this.tab = tab; this.grp = grp;")
    o.append("            this.def = def; this.min = min; this.max = max; this.step = step; this.unit = unit; this.defColor = dc; this.opts = opts;")
    o.append("        }")
    o.append("        public boolean weapon() { return widx >= 0; }")
    o.append("    }\n")
    o.append("    public static final Item[] ITEMS = {")
    for it in items:
        dep = ids[it["dep"]]["slot"] if it.get("dep") else -1
        dc = "null"
        dflt = 0.0
        if it["type"] == T_COLOR:
            dc = "new float[]{%s}" % ", ".join("%sf" % repr(float(x)) for x in it["d"])
        else:
            dflt = float(it["d"])
        opts = "null"
        if it.get("o"):
            opts = "new String[]{%s}" % ", ".join(jstr(x) for x in it["o"])
        o.append("        new Item(%s, %d, %s, %d, %d, %d, %d, %d, %sf, %sf, %sf, %sf, %s, %s, %s)," % (
            jstr(it["id"]), it["type"], jstr(it["l"]), it["slot"], it["widx"], dep, it["tab"], it["grp"],
            repr(dflt), repr(float(it.get("min", 0))), repr(float(it.get("max", 1))), repr(float(it.get("step", 1))),
            jstr(it.get("u", "")), dc, opts))
    o.append("    };\n")
    o.append("    public static final String[] TAB_IDS = {%s};" % ", ".join(jstr(t["id"]) for t in d["tabs"]))
    o.append("    public static final String[] TAB_TITLES = {%s};" % ", ".join(jstr(t["title"]) for t in d["tabs"]))
    o.append("    public static final String[] TAB_ICONS = {%s};" % ", ".join(jstr(t["icon"]) for t in d["tabs"]))
    o.append("    public static final String[] TAB_CUSTOM = {%s};" % ", ".join(jstr(t.get("custom", "")) for t in d["tabs"]))
    o.append("    public static final String[][] GROUP_TITLES = {")
    for t in d["tabs"]:
        o.append("        {%s}," % ", ".join(jstr(g["title"]) for g in t["groups"]))
    o.append("    };\n")
    o.append("    public static final String[] W_IDS = {%s};" % ", ".join(jstr(w["id"]) for w in weapons))
    o.append("    public static final String[] W_NAMES = {%s};" % ", ".join(jstr(w["name"]) for w in weapons))
    o.append("    public static final int[] W_CATS = {%s};" % ", ".join(str(CATS.index(w["cat"])) for w in weapons))
    o.append("    public static final String[] CATS = {%s};" % ", ".join(jstr(c) for c in CATS))
    o.append("    public static final String[][] W_KEYS = {")
    for w in weapons:
        o.append("        {%s}," % ", ".join(jstr(k) for k in w["keys"]))
    o.append("    };\n")
    o.append("    public static float[] defaults() {")
    o.append("        float[] v = new float[TOTAL];")
    o.append("        for (Item it : ITEMS) {")
    o.append("            if (it.type == T_COLOR) { for (int k = 0; k < 4; k++) v[it.slot + k] = it.defColor[k]; } else v[it.slot] = it.def;")
    o.append("        }")
    o.append("        for (int w = 0; w < W_COUNT; w++) for (Item it : ITEMS) if (it.widx >= 0) v[W_BASE + w * W_STRIDE + 1 + it.widx] = it.def;")
    o.append("        return v;")
    o.append("    }")
    o.append("")
    o.append("    public static int wSlot(int weapon, Item it) { return W_BASE + weapon * W_STRIDE + 1 + it.widx; }")
    o.append("    public static int wFlag(int weapon) { return W_BASE + weapon * W_STRIDE; }")
    o.append("}")
    return "\n".join(o) + "\n"


def gen_cpp(d, weapons, items, ids, n, wk):
    o = []
    o.append("// GENERATED by tools/gen_cfg.py from config/schema.json - do not edit")
    o.append("#pragma once")
    o.append("namespace cfg {")
    o.append("constexpr int kN = %d;" % n)
    o.append("constexpr int kWeapons = %d;" % len(weapons))
    o.append("constexpr int kWK = %d;" % wk)
    o.append("constexpr int kWStride = %d;" % (1 + wk))
    o.append("constexpr int kWBase = kN;")
    o.append("constexpr int kTotal = kN + kWeapons * kWStride;")
    for it in items:
        o.append("constexpr int C_%s = %d;" % (cname(it["id"]), it["slot"]))
    o.append("// weapon-scoped item index (or -1) per slot")
    wi = [-1] * n
    for it in items:
        if it["widx"] >= 0:
            wi[it["slot"]] = it["widx"]
    o.append("constexpr int kWIdx[kN] = {%s};" % ", ".join(str(x) for x in wi))
    o.append("struct WeaponDef { const char* id; const char* name; int cat; const char* keys[6]; };")
    o.append("constexpr WeaponDef kWeaponDefs[kWeapons] = {")
    for w in weapons:
        ks = (w["keys"] + ["nullptr"] * 6)[:6]
        ks = [("\"%s\"" % k) if k != "nullptr" else "nullptr" for k in ks]
        o.append("    {\"%s\", \"%s\", %d, {%s}}," % (w["id"], w["name"], CATS.index(w["cat"]), ", ".join(ks)))
    o.append("};")
    o.append("}  // namespace cfg")
    return "\n".join(o) + "\n"


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    schema = os.path.join(root, "config", "schema.json")
    jout = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, "build", "gen", "java", "rage", "so2", "gen", "Cfg.java")
    cout = sys.argv[2] if len(sys.argv) > 2 else os.path.join(root, "build", "gen", "cpp", "cfg_gen.h")
    d, weapons, items, ids, n, wk = load(schema)
    for path, text in ((jout, gen_java(d, weapons, items, ids, n, wk)), (cout, gen_cpp(d, weapons, items, ids, n, wk))):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        open(path, "w", encoding="utf-8").write(text)
    print("cfg: %d slots, %d weapons x %d, total %d" % (n, len(weapons), 1 + wk, n + len(weapons) * (1 + wk)))


if __name__ == "__main__":
    main()
